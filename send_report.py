#!/usr/bin/env python3
"""Рассылка отчёта тестировщикам"""

import asyncio
import sqlite3
import os
from telegram import Bot
from dotenv import load_dotenv

SOFIA_PATH = os.path.dirname(os.path.abspath(__file__))
load_dotenv(os.path.join(SOFIA_PATH, ".env"))

REPORT = """📊 ОТЧЁТ ПО ТЕСТИРОВАНИЮ
Sofia GPT (@humanAINeural_bot)
Дата: 10 января 2026 | Версия: v4.6

📈 СТАТИСТИКА
- Сообщений: 318
- ✅ Good: 70 (65%) | ❌ Bad: 38 (35%)

🔴 ПРОБЛЕМЫ → РЕШЕНИЯ

1️⃣ Неактуальные цены
Было: Сочи 7.6 млн, Крым 7 млн, Алтай 6 млн
Стало: Сочи 8 млн, Крым 9.5 млн, Алтай 9 млн ✅

2️⃣ Отсутствовала Анапа
Добавлена ✅

3️⃣ Формальное приветствие
Стало теплее: "Добрый день! Это София, по недвижимости..." ✅

4️⃣ Странный вопрос "в рублях?"
Убран ✅

5️⃣ Красная Поляна — предлагались квартиры
Теперь только апартаменты (квартир там нет) ✅

6️⃣ Не спрашивали про первый взнос
Добавлен шаг в квалификацию ✅

7️⃣ "100%" непонятно
Заменено на "полная оплата" ✅

8️⃣ Повторы после договорённости о созвоне
После договорённости бот сам вопросы не задаёт ✅

⚠️ СПОРНЫЙ МОМЕНТ
"Капитализация" vs "Рост стоимости" — сейчас: "рост стоимости"

🆕 НОВОЕ
🎤 Голосовой ввод — клиенты могут отправлять голосовые сообщения!

✅ ЧТО ПРОВЕРИТЬ
- Приветствие теплее?
- Цены актуальные?
- Анапа в локациях?
- Спрашивает про первый взнос?
- Не спрашивает "в рублях?"
- Красная Поляна — только апартаменты?
- После созвона не спамит повторами?
- Голосовые работают?

Продолжайте тестировать, чем больше вы общаетесь о недвижимости с Софьей и ставите оценки, тем умнее она становится."""


async def main():
    bot = Bot(token=os.getenv("TELEGRAM_BOT_TOKEN"))
    conn = sqlite3.connect(os.path.join(SOFIA_PATH, "sofia_gpt.db"))
    users = conn.execute("SELECT user_id FROM users").fetchall()
    conn.close()

    for (user_id,) in users:
        try:
            await bot.send_message(chat_id=user_id, text=REPORT)
            print(f"✅ Отправлено {user_id}")
        except Exception as e:
            print(f"❌ {user_id}: {e}")


if __name__ == "__main__":
    asyncio.run(main())
