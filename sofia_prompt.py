def _format_known_facts(known_facts: dict) -> str:
    """Форматирует известные факты для промпта"""
    if not known_facts:
        return "— пока ничего не известно"
    
    lines = []
    for field, data in known_facts.items():
        if isinstance(data, dict):
            lines.append(f"— {field}: {data.get('value', 'н/д')} ({data.get('confidence', 'н/д')})")
        else:
            lines.append(f"— {field}: {data}")
    
    return "\n".join(lines) if lines else "— пока ничего не известно"
