def get_time_context():
    hour = datetime.now().hour
    if 5 <= hour < 12:
        return {"period": "утро", "mood": "энергичная, позитивная"}
    elif 12 <= hour < 18:
        return {"period": "день", "mood": "рабочий режим, собранная"}
    else:
        return {"period": "вечер", "mood": "чуть более расслабленная, но на связи"}


