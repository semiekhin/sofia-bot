def format_state_summary(state) -> str:
    """Форматирует известную информацию о клиенте."""
    
    facts = []
    
    # Обязательные
    if state.goal:
        goal_text = "инвестиция" if state.goal == "investment" else "для себя"
        facts.append(f"✓ Цель: {goal_text}")
    else:
        facts.append("✗ Цель: не известна")
    
    if state.budget:
        facts.append(f"✓ Бюджет: {state.budget / 1_000_000:.0f} млн ₽")
    else:
        facts.append("✗ Бюджет: не известен")
    
    if state.payment_type:
        payment_map = {"full": "полная", "mortgage": "ипотека", "installment": "рассрочка", "flexible": "гибкий"}
        facts.append(f"✓ Оплата: {payment_map.get(state.payment_type, state.payment_type)}")
    else:
        facts.append("✗ Оплата: не известна")
    
    # Дополнительные
    if state.location:
        facts.append(f"• Локация: {state.location}")
    
    if getattr(state, 'strategy', None):
        facts.append(f"• Стратегия: {state.strategy}")
    
    if state.lpr:
        facts.append(f"• ЛПР: {state.lpr}")
    
    # Счётчик отказов
    materials_count = getattr(state, 'materials_request_count', 0) or 0
    if materials_count == 1:
        facts.append("")
        facts.append("⚠️ БЫЛ 1 ОТКАЗ ОТ СОЗВОНА")
        facts.append("→ Задай доп. вопросы (стадия/локация), потом повторно предложи созвон")
    elif materials_count >= 2:
        facts.append("")
        facts.append("🛑 БЫЛО 2+ ОТКАЗА ОТ СОЗВОНА")
        facts.append("→ НЕ предлагай созвон! Заверши с подборкой")
    
    if getattr(state, 'meeting_agreed', False):
        facts.append("")
        facts.append("✅ СОГЛАСИЛСЯ НА СОЗВОН — уточни время")
    
    if getattr(state, 'dialog_finished', False):
        facts.append("")
        facts.append("⛔ ДИАЛОГ ЗАВЕРШЁН")
    
    return "\n".join(facts)


def format_history_for_prompt(messages: list, limit: int = 100) -> str:
    recent = messages[-limit:] if len(messages) > limit else messages
    lines = []
    for msg in recent:
        role = "Клиент" if msg.get("role") == "user" else "София"
        lines.append(f"{role}: {msg.get('content', '')}")
    return "\n".join(lines)
